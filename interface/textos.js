export const IDIOMAS = Object.keys(textos);

/** Idioma inicial: o salvo no navegador, senão o do sistema, senão inglês. */
export function idiomaInicial() {
  const salvo = localStorage.getItem("naoplanar.idioma");
  if (salvo && textos[salvo]) return salvo;
  return navigator.language?.toLowerCase().startsWith("pt") ? "pt-BR" : "en";
}

export function criarTradutor(idioma) {
  const t = textos[idioma] ?? textos.en;
  const local = idioma === "pt-BR" ? "pt-BR" : "en-US";
  const numero = (v) => Number.isInteger(v) ? v.toLocaleString(local) : v.toLocaleString(local, { minimumFractionDigits: 1, maximumFractionDigits: 1 });
  return (chave, valores = {}) =>
    (t[chave] ?? textos["pt-BR"][chave] ?? chave).replace(/\{(\w+)\}/g, (_, k) => {
      const v = valores[k];
      if (v === undefined) return `{${k}}`;
      return typeof v === "number" ? numero(v) : String(v);
    });
}
